// Partner pages (task 304, 2026-11-16). ONE COMMAND after editing the list in assets/partners.js:
//
//   node .tools/partner-pages.cjs            writes <name>.html at the site root for every listed name, deletes the page of any
//                                            name no longer listed, and changes nothing else
//   node .tools/partner-pages.cjs --check    changes nothing; exits 1 if the pages and the list disagree (used by .qa/partners-check.cjs)
//
// Why a page per name: GitHub Pages serves illi.world/<name> from <name>.html with status 200, so link previews (Slack, X,
// iMessage, YouTube) see a real page with illi's title, description and card image, copied from index.html's own tags at
// generation time. The page then sends the visitor to the home page with the partner's tags, as 404.html does for a listed
// name whose page is missing. It stores nothing and sends nothing. Only files this script made (they carry MARK) are ever
// deleted or overwritten. This folder starts with a dot, so Pages does not publish it.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = process.env.SITE_ROOT ? path.resolve(process.env.SITE_ROOT) : path.resolve(__dirname, "..");   // SITE_ROOT: tests only
const MARK = "<!-- illi partner page: generated by .tools/partner-pages.cjs from assets/partners.js. Do not edit by hand. -->";
const NAME = /^[a-z0-9](?:[a-z0-9-]{0,38}[a-z0-9])$/;

function list() {
  const box = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(root, "assets/partners.js"), "utf8"), box);
  const names = box.window.ILLI_PARTNERS;
  if (!Array.isArray(names)) throw new Error("assets/partners.js does not define window.ILLI_PARTNERS as a list");
  return names;
}
const generated = () =>
  fs.readdirSync(root).filter((f) => f.endsWith(".html") && fs.readFileSync(path.join(root, f), "utf8").includes(MARK));
function homeMeta() {
  const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
  const get = (re, what) => {
    const m = html.match(re);
    if (!m) throw new Error("index.html has no " + what);
    return m[1];
  };
  return {
    title: get(/<title>([^<]+)<\/title>/, "<title>"),
    description: get(/<meta name="description" content="([^"]+)"/, "description"),
    image: get(/<meta property="og:image" content="([^"]+)"/, "og:image"),
    imageW: get(/<meta property="og:image:width" content="([^"]+)"/, "og:image:width"),
    imageH: get(/<meta property="og:image:height" content="([^"]+)"/, "og:image:height"),
    imageAlt: get(/<meta property="og:image:alt" content="([^"]+)"/, "og:image:alt"),
  };
}
function page(name, m) {
  const url = "https://illi.world/" + name;
  const fallback = "/?utm_source=" + name + "&amp;utm_medium=partner&amp;utm_campaign=partners";
  return `<!DOCTYPE html>
<html lang="en">
<head>
${MARK}
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="robots" content="noindex">
<title>${m.title}</title>
<meta name="description" content="${m.description}">
<link rel="canonical" href="https://illi.world/">
<meta property="og:type" content="website">
<meta property="og:url" content="${url}">
<meta property="og:site_name" content="illi">
<meta property="og:title" content="${m.title}">
<meta property="og:description" content="${m.description}">
<meta property="og:image" content="${m.image}">
<meta property="og:image:width" content="${m.imageW}">
<meta property="og:image:height" content="${m.imageH}">
<meta property="og:image:alt" content="${m.imageAlt}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${m.title}">
<meta name="twitter:description" content="${m.description}">
<meta name="twitter:image" content="${m.image}">
<script>
(function () {
  var q = new URLSearchParams(location.search);
  q.set('utm_source', '${name}');
  q.set('utm_medium', 'partner');
  if (!q.get('utm_campaign')) q.set('utm_campaign', 'partners');
  location.replace('/?' + q.toString() + location.hash);
})();
</script>
<noscript><meta http-equiv="refresh" content="0; url=${fallback}"></noscript>
<link rel="icon" href="/favicon.ico" sizes="any">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
</head>
<body>
<p><a href="${fallback}">Continue to illi.world</a></p>
</body>
</html>
`;
}

function plan() {
  const names = list();
  const problems = [];
  const seen = new Set();
  const mine = new Set(generated());
  for (const n of names) {
    if (typeof n !== "string" || !NAME.test(n)) problems.push(`"${n}" is not a valid name (a-z, 0-9, hyphens, 2 to 40 characters)`);
    else if (seen.has(n)) problems.push(`"${n}" is listed twice`);
    else if ((fs.existsSync(path.join(root, n)) || fs.existsSync(path.join(root, n + ".html"))) && !mine.has(n + ".html"))
      problems.push(`"${n}" is already a page or folder on the site, so its link would never reach the partner page`);
    seen.add(n);
  }
  if (problems.length) throw new Error(problems.join("\n"));
  const m = homeMeta();
  const want = new Map(names.map((n) => [n + ".html", page(n, m)]));
  const write = [...want].filter(([f, body]) => !fs.existsSync(path.join(root, f)) || fs.readFileSync(path.join(root, f), "utf8").replace(/\r/g, "") !== body);
  const remove = [...mine].filter((f) => !want.has(f));
  return { names, write, remove };
}

const { names, write, remove } = plan();
if (process.argv.includes("--check")) {
  if (write.length || remove.length) {
    console.log("partner pages out of date: to write " + JSON.stringify(write.map((w) => w[0])) + ", to delete " + JSON.stringify(remove) + ". Run: node .tools/partner-pages.cjs");
    process.exit(1);
  }
  console.log("partner pages match the list (" + names.length + " names)");
} else {
  for (const [f, body] of write) fs.writeFileSync(path.join(root, f), body);
  for (const f of remove) fs.unlinkSync(path.join(root, f));
  console.log(names.length + " names; wrote " + JSON.stringify(write.map((w) => w[0])) + "; deleted " + JSON.stringify(remove));
}
